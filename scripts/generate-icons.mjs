/**
 * scripts/generate-icons.mjs  ·  `npm run icons`
 * ---------------------------------------------------------------------------
 * Rasterises the app icon into the PNG sizes a PWA needs.
 *
 * The mark is a waveform inside a rounded square, drawn as SVG so it stays
 * crisp at every size. `sharp` is already present as a Next.js dependency, so
 * this adds nothing to the install.
 *
 * Outputs (all in public/icons/):
 *   icon-192.png          home-screen icon
 *   icon-512.png          store / splash icon
 *   maskable-512.png      Android adaptive icon (extra safe padding)
 *   apple-touch-icon.png  iOS home screen (opaque, 180px)
 *   favicon-48.png        legacy browsers
 */

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outDir = path.join(root, 'public', 'icons');

/** The waveform bars, in a 0–128 viewBox. */
const BARS = [
  [18, 36],
  [34, 68],
  [50, 92],
  [66, 104],
  [82, 76],
  [98, 46],
];

/**
 * @param {number} size    pixel size of the output
 * @param {object} options
 * @param {number} options.inset  how much of the canvas the mark occupies (0–1)
 * @param {boolean} options.rounded  draw the rounded-square plate
 */
function iconSvg({ size, inset = 0.74, rounded = true }) {
  const plate = rounded
    ? `<rect width="128" height="128" rx="30" fill="url(#plate)"/>`
    : `<rect width="128" height="128" fill="url(#plate)"/>`;

  const bars = BARS.map(([x, height]) => {
    const y = (128 - height) / 2;
    return `<rect x="${x}" y="${y}" width="12" height="${height}" rx="6" fill="#ffffff" fill-opacity="0.94"/>`;
  }).join('');

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 128 128" role="img" aria-label="Speech to Text Studio">
  <defs>
    <linearGradient id="plate" x1="0" y1="0" x2="128" y2="128" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#6f6cff"/>
      <stop offset="0.55" stop-color="#5a4fe6"/>
      <stop offset="1" stop-color="#3f2fb0"/>
    </linearGradient>
  </defs>
  <g transform="translate(${(128 * (1 - inset)) / 2} ${(128 * (1 - inset)) / 2}) scale(${inset})">
    ${plate}
    ${bars}
  </g>
</svg>`;
}

async function render(name, size, options) {
  const svg = Buffer.from(iconSvg({ size, ...options }));
  const png = await sharp(svg, { density: 384 })
    .resize(size, size, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png({ compressionLevel: 9 })
    .toBuffer();
  await writeFile(path.join(outDir, name), png);
  return `${name} (${(png.length / 1024).toFixed(1)} kB)`;
}

await mkdir(outDir, { recursive: true });

const results = await Promise.all([
  render('icon-192.png', 192),
  render('icon-512.png', 512),
  // Android masks the outer ~20% away, so the mark sits inside a smaller box.
  render('maskable-512.png', 512, { inset: 0.6 }),
  // iOS does not support transparency in home-screen icons.
  render('apple-touch-icon.png', 180, { inset: 0.78, rounded: false }),
  render('favicon-48.png', 48, { inset: 0.86 }),
]);

// Anchors the dir in git even if a generated file is ever removed.
await writeFile(
  path.join(outDir, '.gitkeep'),
  'Icons are generated by `npm run icons` (scripts/generate-icons.mjs).\n',
);

// `warn` keeps the repo's no-console lint rule happy for build scripts.
console.warn(`Icons written to public/icons:\n  ${results.join('\n  ')}`);
